import React from "react";
import { interpolate, useCurrentFrame } from "remotion";
import { Scene } from "../components/Frame";
import { appearAt } from "../components/Trace";
import { D } from "../data";
import { C, F, clamp, easeOut } from "../theme";

const Tile: React.FC<{ i: number; value: string; label: string; sub: string; tone: string }> = ({ i, value, label, sub, tone }) => {
  const frame = useCurrentFrame();
  const p = appearAt(frame, 14 + i * 16, 18);
  return (
    <div style={{ background: C.surface, border: `1.5px solid ${C.line}`, borderRadius: 18, padding: "34px 34px 30px",
      display: "grid", gap: 14, alignContent: "start", opacity: p, translate: `0px ${(1 - p) * 30}px` }}>
      <div style={{ fontFamily: F.cond, fontWeight: 700, fontSize: 116, lineHeight: 0.95, color: tone,
        fontVariantNumeric: "tabular-nums" }}>{value}</div>
      <div style={{ fontSize: 32, fontWeight: 600, lineHeight: 1.25 }}>{label}</div>
      <div style={{ fontFamily: F.mono, fontSize: 21, color: C.muted, lineHeight: 1.45 }}>{sub}</div>
    </div>
  );
};

export const Metrics: React.FC = () => {
  const frame = useCurrentFrame();
  const m = D.metrics;
  const found = Math.round(interpolate(frame, [20, 70], [0, m.found], { ...clamp, easing: easeOut }));
  return (
    <Scene chapter={6} captions={[
      { from: 6, to: 236, text: "Scored against five client variants with known defects: same budget, three seeds, every number regenerated by one script." },
    ]}>
      <div style={{ display: "grid", gridTemplateColumns: "repeat(4, 1fr)", gap: 24, height: "100%", alignContent: "center", paddingBottom: 40 }}>
        <Tile i={0} value={`${found}/${m.defective}`} label="seeded defects found" sub="explorations of defective clients" tone={C.good} />
        <Tile i={1} value={`${m.false_alarms}/${m.correct}`} label="false alarms" sub="explorations of correct clients" tone={C.ink} />
        <Tile i={2} value={`${Math.round(m.record_us)} µs`} label="to record one call" sub={`${m.share_percent}% of a local HTTP call · ${m.disk_bytes} B per event on disk`} tone={C.accent} />
        <Tile i={3} value={m.deterministic ? "same" : "differs"} label="seed in, results out" sub="same seed → same schedules and findings" tone={C.ink} />
      </div>
    </Scene>
  );
};
